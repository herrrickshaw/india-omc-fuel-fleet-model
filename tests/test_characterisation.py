"""Characterisation tests: the refactored modules must reproduce the tracked outputs.

The tracked files under outputs/ and vahan/ were generated by the ORIGINAL
(pre-refactor) scripts; each test regenerates into a tmp dir and compares
byte-for-byte. No network access: all inputs are constants in the modules.
"""
from __future__ import annotations

from pathlib import Path

import pytest

import analyze_vahan_fuel as vahan
import energy_blend_comparison as energy
import fleet_from_fuel as fleet
import omc_model as omc

ROOT = Path(__file__).resolve().parents[1]
OUTPUTS = ROOT / "outputs"
VAHAN_OUT = ROOT / "vahan" / "outputs"


def same(generated: Path, tracked: Path) -> None:
    assert generated.read_bytes() == tracked.read_bytes(), tracked.name


@pytest.mark.parametrize("name", ["scenarios.csv", "yoy_projection.csv",
                                  "blend_mix_scenarios.csv", "omc_profitability_report.md"])
def test_omc_model_outputs_identical(tmp_path, name):
    result = omc.run_model()
    omc.write_csvs(result, tmp_path)
    omc.write_md(result, tmp_path)
    same(tmp_path / name, OUTPUTS / name)


def test_omc_model_headline_numbers():
    r = omc.run_model()
    assert round(r["base"]["tot_inc"]) == round(omc.omc_income(
        omc.bnL_from_MMT(40.0, 0.74), omc.bnL_from_MMT(91.4, 0.83))[2])
    sc = {s["scenario"]: s for s in r["scenarios"]}
    assert sc["E20"]["extra_OMC_income_cr"] == pytest.approx(757, abs=1)   # README/report figure
    assert [p["fy"] for p in r["proj"]][0] == "FY25-26"
    assert r["proj"][0]["yoy_growth_cr"] is None


def test_mix_shares_must_sum_to_one():
    with pytest.raises(AssertionError):
        omc.mix_scenario("bad", (0.5, 0.5, 0.5, 0.0), 1.0)


@pytest.mark.parametrize("name", ["fleet_from_fuel.csv", "fleet_from_fuel.md"])
def test_fleet_outputs_identical(tmp_path, name):
    rows, nonroad = fleet.build_rows()
    summ = fleet.summarise(rows, nonroad)
    fleet.write_csv(rows, tmp_path)
    (tmp_path / "fleet_from_fuel.md").write_text(fleet.render_md(rows, summ))
    same(tmp_path / name, OUTPUTS / name)


def test_fleet_total_is_sum_of_parts():
    rows, nonroad = fleet.build_rows()
    s = fleet.summarise(rows, nonroad)
    assert s["grand_active"] == s["liquid_active"] + s["cng_active"] + s["ev_active"]
    lo, hi = min(s["band"].values()), max(s["band"].values())
    assert lo < s["grand_active"] < hi


@pytest.mark.parametrize("name", ["fuel_group_summary.csv", "fuel_by_class.csv", "vahan_fuel_analysis.md"])
def test_vahan_outputs_identical(tmp_path, name):
    vahan.check_integrity()
    grp, cgrp = vahan.group_totals(vahan.tot), vahan.group_totals(vahan.CUM)
    class_grp, class_tot = vahan.class_breakdown()
    vahan.write_summary_csvs(grp, cgrp, class_grp, class_tot, tmp_path)
    (tmp_path / "vahan_fuel_analysis.md").write_text(vahan.render_md(grp, cgrp, class_grp, class_tot))
    same(tmp_path / name, VAHAN_OUT / name)


def test_vahan_raw_csvs_identical(tmp_path):
    vahan.write_raw_csvs(tmp_path)
    for name in ("vahan_fuel_registrations_cy2025.csv", "vahan_fuel_registrations_cumulative.csv"):
        same(tmp_path / name, ROOT / "vahan" / name)


def test_vahan_classify():
    assert vahan.classify("PETROL(E20)/CNG") == "Petrol + gas bi-fuel (CNG/LPG)"
    assert vahan.classify("PURE EV") == "Electric (BEV/PHEV)"
    assert vahan.is_e20("PETROL(E20)") and not vahan.is_e20("PETROL")


@pytest.mark.parametrize("name", ["energy_blend_comparison.md", "fuel_energy_table.csv",
                                  "blend_dilution_fiscal.csv", "blend_walk_incremental.csv",
                                  "diesel_biodiesel_fiscal.csv"])
def test_energy_outputs_identical(tmp_path, name):
    energy.write_outputs(tmp_path)
    same(tmp_path / name, OUTPUTS / name)


def test_energy_blend_row_math():
    r = energy.blend_row("E20", 32.0, 21.0, 0.2, "petrol")
    assert r["energy_drop_pct"] == pytest.approx(6.88, abs=0.01)
